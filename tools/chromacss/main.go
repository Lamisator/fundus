// Command chromacss writes web/static/chroma.css: syntax highlighting for
// the light theme and, scoped under [data-theme="dark"], the dark theme.
//
//	go run ./tools/chromacss > web/static/chroma.css
package main

import (
	"bytes"
	"fmt"
	"os"
	"regexp"

	"github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

func main() {
	f := html.New(html.WithClasses(true))
	var light, dark bytes.Buffer
	if err := f.WriteCSS(&light, styles.Get("github")); err != nil {
		panic(err)
	}
	if err := f.WriteCSS(&dark, styles.Get("github-dark")); err != nil {
		panic(err)
	}
	// Backgrounds come from the page theme, not the chroma style.
	bg := regexp.MustCompile(`background-color: #[0-9a-fA-F]+;?`)
	sel := regexp.MustCompile(`(?m)^(/\*[^*]*\*/ )?\.(chroma|bg)`)
	fmt.Println("/* generated by tools/chromacss - do not edit */")
	os.Stdout.Write(bg.ReplaceAll(light.Bytes(), nil))
	os.Stdout.Write(sel.ReplaceAll(bg.ReplaceAll(dark.Bytes(), nil), []byte(`$1:root[data-theme="dark"] .$2`)))
}
